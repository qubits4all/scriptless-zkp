"""
Implements an interactive zero-knowledge (ZK) range proof protocol for proving that a committed integer `x` value falls
within a specified range `[0, q)`, for an integer `x` in `[0, l]` where ``l := floor(q/3)``.

This module implements the prover and verifier client components of the ZK range proof protocol (`ZKRangeProofProver`
and `ZKRangeProofVerifier`), as well as the common context that encapsulates pre-shared parameters. The prover and
verifier clients each maintain their own secret local state and protocol session state, which is encapsulated in the
`ZKRangeProofProverSession` and `ZKRangeProofVerifierSession` session classes, respectively.

This session state can be stored in a local database or other persistent storage controlled by the prover or verifier,
respectively, keyed by its unique `session_id` (i.e., unique to the prover or verifier, but not necessarily equal).
Alternatively, if the ZK range proof protocol is being executed by a delegated party on behalf of either party, this
session state can be stored in a database controlled by that delegated party. If building a client application that can
recover from crashes or restarts, the prover or verifier client's session state should be persisted to disk or a
database after each protocol step, along with an encrypted copy of its secret local state.

The prover and verifier clients use their corresponding session object, along with their secret local state,
respectively, to interactively execute the ZK range proof protocol. At the end of a successful protocol execution, for
a prover-committed value `x` in the prescribed range `[0, l]`, the prover will have proven to the verifier that the
committed value `x` falls within the specified range `[0, q)` to be proven.

The interactive protocol implemented here is that of Yehuda Lindell, as described in his paper:
"Fast Secure Two-Party ECDSA Signing" (https://eprint.iacr.org/2019/114.pdf).
"""

