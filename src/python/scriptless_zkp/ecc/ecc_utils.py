"""
Helper functions for working with the elliptic curves used in elliptic curve cryptography (ECC).
"""
from __future__ import annotations

from typing import Optional

from Cryptodome.PublicKey import ECC
from Cryptodome.Random import random

from scriptless_zkp.ecc.exceptions import InvalidECCPointException
from scriptless_zkp.ecc.weierstrass_curves import WeierstrassEllipticCurveConfig


def generate_random_nonce(curve_config: WeierstrassEllipticCurveConfig, exclude_one: bool = False) -> int:
    """
    Generates a random big integer in the range `[1, q-1]` inclusive (or `[2, q-1]` if `exclude_one` is `True`), where
    `q` is the configured elliptic curve sub-group's order (i.e., `|<G>|` where `<G>` is the sub-group generated by the
    public base point `G`).
    :param curve_config: elliptic curve configuration to be used when generating the random private nonce scalar.
    :param exclude_one: flag indicating whether the value `1` should be excluded from the range of generated nonces.
    :return: a random big integer in the range `[1, q-1]` inclusive (or `[2, q-1]` if `exclude_one=True`), where `q` is
             the configured elliptic curve sub-group's order.
    """
    if exclude_one:
        return random.randint(2, curve_config.order - 1)
    else:
        return random.randint(1, curve_config.order - 1)


def generate_random_nonce_pair(
        curve_config: WeierstrassEllipticCurveConfig,
        ecc_base_point: Optional[ECC.EccPoint] = None,
        exclude_one: bool = False
) -> (int, ECC.EccPoint):
    """
    Generates a random private nonce scalar (big integer) and an associated nonce elliptic curve (EC) point, constructed
    using the provided EC base point (as `nonce_point := nonce * base_point`), defaulting to the configured elliptic
    curve's public generator `G` if an EC base point is not provided.
    :param curve_config: elliptic curve configuration to be used when generating the random nonce EC point.
    :param ecc_base_point: the ECC base point to be used for constructing the nonce EC point
           (as `nonce_point := nonce * base_point`), defaulting to the configured elliptic curve sub-group's
           generator `G` if not provided.
    :param exclude_one: flag indicating whether the value `1` should be excluded from the range of generated nonces.
    :return: (int, ECC.EccPoint) a randomly-generated nonce and an associated nonce EC point, constructed using
             the provided EC base point (or the configured curve's public generator `G` if not provided).
    """
    base_point: ECC.EccPoint = ecc_base_point if ecc_base_point else curve_config.base_point

    while True:
        private_nonce: int = generate_random_nonce(curve_config, exclude_one=exclude_one)
        nonce_point: ECC.EccPoint = base_point * private_nonce

        # Ensure the generated nonce point is not the elliptic curve group's unit (i.e., the point-at-infinity).
        if not nonce_point.is_point_at_infinity():
            break

    return private_nonce, nonce_point


def encode_ecc_point(
        curve_config: WeierstrassEllipticCurveConfig,
        ecc_point: ECC.EccPoint,
        compress: bool = False
) -> bytes:
    return ecc_point_to_pubkey(curve_config, ecc_point).export_key(format='SEC1', compress=compress)


def ecc_point_to_pubkey(curve_config: WeierstrassEllipticCurveConfig, ecc_point: ECC.EccPoint) -> ECC.EccKey:
    if curve_config.is_point_on_curve(ecc_point):
        return ECC.construct(curve=curve_config.curve, point_x=ecc_point.x, point_y=ecc_point.y)
    else:
        raise InvalidECCPointException(
            ecc_curve_name=curve_config.curve,
            point_x=ecc_point.x,
            point_y=ecc_point.y
        )


def encode_public_key(public_key: ECC.EccKey) -> bytes:
    if public_key.has_private():
        return public_key.public_key().export_key(format='SEC1')
    else:
        return public_key.export_key(format='SEC1')


def ecc_point_to_hex(ecc_point: ECC.EccPoint) -> str:
    """
    Encodes the provided ECC point for use in debugging messages, using hexadecimal encoding for each coordinate.
    :param ecc_point: the ECC point to be encoded in hexadecimal.
    :return: a string representation of the ECC point, with each coordinate encoded in hexadecimal.
    """
    return f"({hex(ecc_point.x)}, {hex(ecc_point.y)})"
